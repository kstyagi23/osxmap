def _reviewed_entries():
    entries = {}
    for ids, access, workflow, blockers, requires_path in _GROUPS:
        for product_id in ids:
            if product_id in entries:
                raise ValueError("Duplicate readiness review: " + product_id)
            product = PRODUCTS[product_id]
            entries[product_id] = ReviewedReadiness(
                (access, workflow), blockers, product.dependencies,
                product.capabilities, product.kind, requires_path)
    if set(entries) != set(PRODUCTS):
        raise ValueError("Readiness review must cover the exact catalogue IDs")
    return MappingProxyType(entries)


REVIEWED_ENTRIES = _reviewed_entries()


def readiness(product_id, installed: set, configured_paths: set):
    """Return detached JSON fields, never activation authority or credential state.

    ``installed`` contains exact registry dependency keys for reviewed connected
    adapters/importers/software, not merely a user-selected product. For workflows
    needing explicit operator endpoints or schedule/feed paths, ``configured_paths``
    contains exact product IDs attested by backend review, not paths or URLs.
    Documented prerequisites qualify as a setup plan, not an executable importer.
    A connected local workflow may accept preconverted reviewed GeoJSON/manifests
    or validate an asset hash only; it does not certify all listed source codecs.
    """
    entry = REVIEWED_ENTRIES[product_id]
    if not isinstance(installed, (set, frozenset)) or not isinstance(configured_paths, (set, frozenset)):
        raise TypeError("Readiness inventory must use application-owned sets")
    product = PRODUCTS[product_id]
    blockers = list(product.permission_blockers) + list(entry.blockers)
    missing = [key for key in entry.dependencies if key not in installed]
    for dependency in missing:
        blockers.append("Missing " + dependency + ": " + entry.setup_steps[1])
    missing_path = entry.requires_path and product_id not in configured_paths
    if missing_path:
        blockers.append("No reviewed endpoint/feed/schedule configuration for " + product_id + ": " + entry.setup_steps[0])
    if product.permission_blockers or entry.blockers:
        status = "permission_blocked"
    elif missing or missing_path:
        status = "needs_setup"
    elif entry.kind == "library":
        status = "loaded_dependency"
    elif entry.kind in {"download", "asset", "self_hosted"}:
        status = "connected_workflow"
    else:
        status = "connected_adapter"
    return {"implementation_status": status,
            "setup_steps": list(entry.setup_steps), "blockers": blockers,
            "capabilities": list(entry.capabilities), "live_tested": False}
